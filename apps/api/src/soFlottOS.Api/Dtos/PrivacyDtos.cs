using System.ComponentModel.DataAnnotations;
using soFlottOS.Api.Domain;

namespace soFlottOS.Api.Dtos;

// ---------------------------------------------------------------------------
// Cookie-consent evidence and GDPR data-subject requests.
// Consent payloads carry no personal data on purpose: the id is a random value the
// browser generated, so a record can never be linked back to a person.
// ---------------------------------------------------------------------------

/// <summary>One cookie-consent decision as sent by the browser. "Necessary" cookies are always on and not sent.</summary>
public sealed record RecordConsentRequest
{
    /// <summary>Random id generated by the browser and kept in its consent cookie. Sending it twice is harmless.</summary>
    public Guid Id { get; init; }

    /// <summary>The visitor's previous decision, if any.</summary>
    public Guid? PreviousId { get; init; }

    [Required, MaxLength(20)]
    public string Version { get; init; } = string.Empty;

    public ConsentAction Action { get; init; }

    public bool Analytics { get; init; }

    public bool Marketing { get; init; }

    public bool Preferences { get; init; }
}

/// <summary>A stored consent decision, returned to admins when they audit a visitor's consent chain.</summary>
public sealed record ConsentHistoryItemResponse(
    Guid Id,
    Guid? PreviousId,
    string Version,
    ConsentAction Action,
    bool Analytics,
    bool Marketing,
    bool Preferences,
    DateTimeOffset CreatedAt);

/// <summary>Public privacy form: someone exercising a GDPR right.</summary>
public sealed record CreatePrivacyRequestRequest
{
    public PrivacyRequestType Type { get; init; }

    [Required, EmailAddress, MaxLength(254)]
    public string Email { get; init; } = string.Empty;

    [MaxLength(120)]
    public string? FullName { get; init; }

    [MaxLength(2000)]
    public string? Message { get; init; }

    /// <summary>"de" or "en". Anything else is treated as "de".</summary>
    [MaxLength(10)]
    public string? Locale { get; init; }
}

/// <summary>What the requester gets back after submitting. The id is their reference.</summary>
public sealed record PrivacyRequestCreatedResponse(
    Guid Id,
    PrivacyRequestStatus Status,
    DateTimeOffset CreatedAt,
    DateTimeOffset DueAt);

/// <summary>Public status lookup by reference id. Deliberately contains no personal data.</summary>
public sealed record PrivacyRequestStatusResponse(
    Guid Id,
    PrivacyRequestType Type,
    PrivacyRequestStatus Status,
    DateTimeOffset CreatedAt,
    DateTimeOffset DueAt,
    DateTimeOffset? CompletedAt);

/// <summary>Everything an admin needs to handle a request, including the requester's details.</summary>
public sealed record PrivacyRequestAdminResponse(
    Guid Id,
    PrivacyRequestType Type,
    PrivacyRequestStatus Status,
    string Email,
    string? FullName,
    string? Message,
    string Locale,
    string? HandlerNote,
    DateTimeOffset CreatedAt,
    DateTimeOffset UpdatedAt,
    DateTimeOffset DueAt,
    DateTimeOffset? CompletedAt);

public sealed record UpdatePrivacyRequestStatusRequest
{
    public PrivacyRequestStatus Status { get; init; }

    /// <summary>Internal note, never shown to the requester.</summary>
    [MaxLength(2000)]
    public string? HandlerNote { get; init; }
}
