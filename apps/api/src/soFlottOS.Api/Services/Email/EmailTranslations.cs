    public static string Normalize(string? locale) =>
        string.Equals(locale, "en", StringComparison.OrdinalIgnoreCase) ? "en" : "de";

    public static string Language(string locale) => Normalize(locale);

    public static CultureInfo Culture(string locale) =>
        Normalize(locale) == "en" ? EnglishCulture : GermanCulture;

    public static string Get(string locale, string key)
    {
        if (!Copy.TryGetValue(key, out var translation))
            throw new ArgumentOutOfRangeException(nameof(key), key, "Unknown email translation key.");
        return Normalize(locale) == "en" ? translation.English : translation.German;
    }
